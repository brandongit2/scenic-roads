//! Phases' names before task #844 (30 Oct 2026), as the timings records hold them: a phase was
//! named by what it did as done ("the sources' windows read"); now as doing it ("reading the
//! sources' windows"), the build page, job cards and logs alike. A record read (crate::timings'
//! `PhaseRec`, `Gap`) takes the new name of an old one here, so a step's history keeps its phases.

/// The new name of a phase named `name` before task #844 (itself when it wasn't renamed).
pub fn current(name: &str) -> std::borrow::Cow<'_, str> {
    if let Ok(i) = RENAMED.binary_search_by(|(old, _)| (*old).cmp(name)) {
        return RENAMED[i].1.into();
    }
    // (A dataset's sampling: "<dataset> sampled", crate::dem::generic.)
    match name.strip_suffix(" sampled") {
        Some(ds) if !ds.is_empty() && !ds.contains(' ') => format!("sampling {ds}").into(),
        _ => name.into(),
    }
}

